-- Mỗi thay đổi của văn bản (tạo, sửa, xóa; sau này thêm chuyển trạng thái) ghi một dòng. Chỉ thêm, không sửa/xóa.
CREATE TABLE document_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT      NOT NULL REFERENCES documents (id),
    action      VARCHAR(20) NOT NULL,
    from_status VARCHAR(30),                 -- NULL khi tạo mới
    to_status   VARCHAR(30) NOT NULL,
    actor_id    BIGINT      NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_document_history_action CHECK (action IN ('CREATE', 'UPDATE', 'DELETE'))
);

CREATE INDEX idx_document_history_document ON document_history (document_id);
