-- Một bảng dùng chung cho công văn đến / đi / nội bộ. Ba cột công văn đến (incoming_number, received_date, sender) để NULL khi direction != INCOMING.
-- doc_type_id, urgency_id, confidentiality_id là id danh mục của category-service (khác DB nên không có FK).
CREATE TABLE documents (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction           VARCHAR(20)   NOT NULL,
    doc_number          VARCHAR(100),                -- cấp khi công bố, bản thảo để trống
    doc_type_id         BIGINT        NOT NULL,
    summary             VARCHAR(2000) NOT NULL,
    urgency_id          BIGINT        NOT NULL,
    confidentiality_id  BIGINT        NOT NULL,
    department_id       BIGINT        NOT NULL,      -- đơn vị của owner lúc tạo
    owner_id            BIGINT        NOT NULL,
    dossier_id          BIGINT REFERENCES dossiers (id),
    status              VARCHAR(30)   NOT NULL DEFAULT 'DRAFT',
    current_approver_id BIGINT,
    issue_date          DATE,
    is_revoked          BOOLEAN       NOT NULL DEFAULT FALSE,

    -- Công văn đến (SRS FR6.1: số đến, ngày đến, nơi gửi)
    incoming_number     VARCHAR(100),
    received_date       DATE,
    sender              VARCHAR(255),

    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at          TIMESTAMP WITH TIME ZONE,    -- xóa mềm

    CONSTRAINT chk_documents_direction CHECK (direction IN ('INCOMING', 'OUTGOING', 'INTERNAL')),
    CONSTRAINT chk_documents_status CHECK (status IN ('DRAFT', 'PENDING_PUBLICATION', 'PUBLISHED'))
);

CREATE INDEX idx_documents_owner ON documents (owner_id);
CREATE INDEX idx_documents_department_status ON documents (department_id, status);
