CREATE TABLE attachments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id   BIGINT       NOT NULL REFERENCES documents (id),
    file_group_id VARCHAR(36)  NOT NULL,
    file_name     VARCHAR(255) NOT NULL,
    bucket        VARCHAR(100) NOT NULL,
    storage_key   VARCHAR(500) NOT NULL UNIQUE,
    mime_type     VARCHAR(100) NOT NULL,
    file_size     BIGINT       NOT NULL CHECK (file_size > 0),
    version_no    INT          NOT NULL DEFAULT 1 CHECK (version_no >= 1),
    is_current    BOOLEAN      NOT NULL DEFAULT TRUE,
    uploaded_by   BIGINT       NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_attachments_doc_group_version UNIQUE (document_id, file_group_id, version_no)
);

CREATE INDEX idx_attachments_doc_current ON attachments (document_id, is_current);
CREATE INDEX idx_attachments_doc_group_ver ON attachments (document_id, file_group_id, version_no DESC);
